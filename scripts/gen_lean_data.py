"""Generate AME125/Data.lean from the authors' matrix and the certificates.

Usage: python scripts/gen_lean_data.py data/theta_ame125.txt data/certs.txt AME125/Data.lean

The Lean file holds the 144 entries of the matrix, row by row, and the 924 certificates as
pairs `(mask, entries)`, in the order of data/certs.txt. Each certificate line keeps its mask in
binary as a comment. The file is generated and should not be edited by hand.
"""
import sys

theta_path, certs_path, out_path = sys.argv[1:4]
g = [list(map(int, line.split())) for line in open(theta_path) if line.strip()]
certs = [list(map(int, line.split())) for line in open(certs_path) if line.strip()]

header = '''/-
Copyright (c) 2026 Zayn Blore. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Zayn Blore
-/
module

public import Mathlib

/-!
# The data: the graph matrix and the cut certificates

`thetaRows` is the 12 × 12 matrix over `ZMod 5` of the AME(12,5) graph state of S. Bevins and
Y. Bidav (arXiv:2608.05781), one list per row, entries in `0, …, 4`, from
`data/theta_ame125.txt`, which is the file in the authors' reproducibility package (MIT licence;
see `data/SOURCE.md`).

`certs` has one entry for each set `A` of six parties out of twelve: the set as a 12-bit mask
(bit `i` set when party `i` is in `A`) and the 36 entries, row by row, of a 6 × 6 matrix over
`ZMod 5`, entries in `0, …, 4`. Its rows follow the parties outside `A` and its columns the
parties in `A`, both in increasing order. It is the inverse of the block of the matrix between
`A` and the rest (`AME125.certs_ok`). The entries are in increasing order of mask.

This file is generated by `scripts/gen_lean_data.py` from `data/theta_ame125.txt` and
`data/certs.txt` and should not be edited by hand.
-/

@[expose] public section

namespace AME125
'''
lines = [header]
lines.append("/-- The graph matrix of the AME(12,5) state, one list per row. -/")
lines.append("def thetaRows : List (List ℕ) :=")
rows = ["[" + ", ".join(map(str, r)) + "]" for r in g]
lines.append("  [" + rows[0] + ",")
for r in rows[1:-1]:
    lines.append("   " + r + ",")
lines.append("   " + rows[-1] + "]")
lines.append("")
CHUNK = 100
chunks = [certs[i:i + CHUNK] for i in range(0, len(certs), CHUNK)]
for ci, chunk in enumerate(chunks):
    lines.append(f"/-- Cut certificates {ci * CHUNK + 1} to {ci * CHUNK + len(chunk)}: a mask of six "
                 "parties and the inverse of its block. -/")
    lines.append(f"def certs{ci} : List (ℕ × List ℕ) := [")
    for idx, c in enumerate(chunk):
        mask, entries = c[0], c[1:]
        sep = "," if idx < len(chunk) - 1 else ""
        first = ", ".join(map(str, entries[:18]))
        second = ", ".join(map(str, entries[18:]))
        lines.append(f"  ({mask}, [{first}, -- {mask:012b}")
        lines.append(f"    {second}]){sep}")
    lines.append("]")
    lines.append("")
lines.append("/-- All 924 cut certificates, in mask order. -/")
lines.append("def certs : List (ℕ × List ℕ) :=")
lines.append("  " + " ++ ".join(f"certs{ci}" for ci in range(len(chunks))))
lines.append("")
lines.append("end AME125")
lines.append("")
with open(out_path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print(f"wrote {out_path}: {len(g)} rows, {len(certs)} certificates")
